create table public.clientes (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  telefono text not null default '',
  correo text not null,
  creado_en timestamptz not null default now()
);

create table public.ramos (
  id uuid primary key default gen_random_uuid(),
  tamano text not null,
  flores text not null,
  follaje text not null default '',
  extras text not null default '',
  creado_en timestamptz not null default now()
);

create type public.estado_pedido as enum ('recibido', 'confirmado', 'en_preparacion', 'listo');

create table public.pedidos (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  cliente_id uuid not null references public.clientes(id),
  ramo_id uuid not null references public.ramos(id),
  estado public.estado_pedido not null default 'recibido',
  creado_en timestamptz not null default now()
);

create table public.personalizaciones (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null unique references public.pedidos(id) on delete cascade,
  ocasion text not null,
  colores text not null,
  envoltura text not null,
  dedicatoria text not null default '',
  creado_en timestamptz not null default now()
);

create table public.detalles_pedido (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null unique references public.pedidos(id) on delete cascade,
  preferencias text not null,
  observaciones text not null default '',
  instrucciones_armado text not null default '',
  creado_en timestamptz not null default now()
);

alter table public.clientes enable row level security;
alter table public.ramos enable row level security;
alter table public.pedidos enable row level security;
alter table public.personalizaciones enable row level security;
alter table public.detalles_pedido enable row level security;

